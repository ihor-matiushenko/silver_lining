import '../models/reframe_response.dart';

/// 🛡️ LocalSafetyService: 100% Offline 3-Tier Safety & Guardrails Engine (<1ms Pure Dart)
///
/// Mirrors the Python backend's `SafetyService` (`backend/app/services/safety_service.py`)
/// plus output-level refusal detection for our fine-tuned Gemma 3 270M SLM weights.
class LocalSafetyService {
  /// Multi-language keyword set for Tier-1 Self-Harm Crisis Trigger (EN, UK, ES, DE, FR)
  static const List<String> selfHarmKeywords = [
    // English
    'hurt myself',
    'suicide',
    'end it all',
    'end my life',
    'kill myself',
    'want to die',
    'self harm',
    'cut myself',
    // Ukrainian
    'покінчити з життям',
    'вбити себе',
    'суїцид',
    'самогубство',
    'заподіяти собі шкоду',
    'не хочу жити',
    // Spanish
    'matarme',
    'suicidio',
    'quitarme la vida',
    'hacerme daño',
    'no quiero vivir',
    // German
    'mich umbringen',
    'suizid',
    'selbstmord',
    'mein leben beenden',
    // French
    'me tuer',
    'mettre fin à mes jours',
    'me suicider',
    'me faire du mal',
  ];

  /// Tier-2 Crime / Illegal patterns (avoids false positives like "my account was hacked")
  static final List<RegExp> crimePatterns = [
    RegExp(
      r'\b(i\s+stole|i\s+steal|how\s+to\s+steal|how\s+to\s+rob|stole\s+money)\b',
      caseSensitive: false,
    ),
    RegExp(
      r'\b(shoplift|shoplifting|how\s+to\s+shoplift)\b',
      caseSensitive: false,
    ),
    RegExp(
      r'\b(robbed|murder|murdered|how\s+to\s+murder)\b',
      caseSensitive: false,
    ),
    RegExp(
      r'\b(how\s+to\s+hack|hack\s+into|planning\s+to\s+hack)\b',
      caseSensitive: false,
    ),
    RegExp(
      r'\b(commit\s+fraud|how\s+to\s+pirate|pirate\s+software)\b',
      caseSensitive: false,
    ),
    RegExp(
      r'(^|[^\p{L}])(вкрасти|пограбувати|як\s+зламати|вбивство)($|[^\p{L}])',
      caseSensitive: false,
      unicode: true,
    ),
    RegExp(
      r'(^|[^\p{L}])(robar|asesinar|cómo\s+hackear)($|[^\p{L}])',
      caseSensitive: false,
      unicode: true,
    ),
  ];

  /// Output markers emitted by the fine-tuned Gemma 3 270M model when refusing gray-area prompts
  static const List<String> modelRefusalMarkers = [
    '**i cannot',
    'but i cannot',
    'i cannot help you with this request',
    'i cannot provide assistance',
    'cannot provide validation',
    'actions involving theft',
    'i cannot reframe',
    'i cannot assist',
    'i cannot support',
    'я не можу допомогти',
    'не можу переосмислити',
    'no puedo ayudarte',
    'ich kann dir bei dieser anfrage nicht helfen',
    'je ne peux pas vous aider',
  ];

  /// Evaluates input text against Tier-1 (Self-Harm Crisis) and Tier-2 (Crime/Illegal) rules.
  /// Returns `null` if the input is Tier-3 (Safe for On-Device AI Reframing).
  static ReframeResponse? evaluateInputSafety(String inputText) {
    final textLower = inputText.toLowerCase().trim();
    if (textLower.isEmpty) return null;

    // Tier 1: Self-Harm Crisis Shield (988 Emergency Lifeline)
    for (final keyword in selfHarmKeywords) {
      if (textLower.contains(keyword)) {
        return const ReframeResponse(
          isSafe: true,
          safetyCategory: 'self_harm_crisis',
          reframedText: null,
          crisisTriggered: true,
          emergencyHotline: '988',
        );
      }
    }

    // Tier 2: Crime / Illegal Act Policy Refusal
    for (final pattern in crimePatterns) {
      if (pattern.hasMatch(textLower)) {
        return const ReframeResponse(
          isSafe: false,
          safetyCategory: 'crime_refusal',
          reframedText: null,
          crisisTriggered: false,
          emergencyHotline: null,
        );
      }
    }

    // Tier 3: Safe for AI Reframing
    return null;
  }

  /// Inspects raw text generated by the fine-tuned On-Device SLM to detect
  /// baked-in gray-area safety refusals (e.g., roomate wallet theft, academic cheating).
  static bool isModelOutputRefusal(String generatedText) {
    final lower = generatedText.toLowerCase().trim();
    for (final marker in modelRefusalMarkers) {
      if (lower.contains(marker)) {
        return true;
      }
    }
    return false;
  }
}

